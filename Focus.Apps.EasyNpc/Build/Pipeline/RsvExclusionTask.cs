using Focus.Apps.EasyNpc.Profiles;
using Serilog;
using System;
using System.IO.Abstractions;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Focus.Apps.EasyNpc.Build.Pipeline
{
    // Optionally writes a SPID file that adds the RSVIgnore keyword to every NPC given a modded face, so Racial Skin
    // Variance skips them instead of repainting their skin. Harmless without RSV installed.
    public class RsvExclusionTask : BuildTask<RsvExclusionTask.Result>
    {
        // SPID only loads files whose names end in "_DISTR.ini".
        private const string OutputFileName = "EasyNPC Next - RSV Exclusions_DISTR.ini";

        public class Result
        {
            public int ExcludedNpcCount { get; init; }
        }

        // Takes NpcFacesTask.Result so it runs after face customizations are final.
        public delegate RsvExclusionTask Factory(NpcFacesTask.Result faces);

        private readonly IFileSystem fs;
        private readonly ILogger log;

        public RsvExclusionTask(IFileSystem fs, ILogger log, NpcFacesTask.Result faces)
        {
            this.fs = fs;
            this.log = log;
        }

        protected override async Task<Result> Run(BuildSettings settings)
        {
            if (!settings.GenerateRsvExclusions)
                return new Result { ExcludedNpcCount = 0 };

            // NPCs given a non-vanilla face or a facegen override.
            var npcs = settings.IncludedNpcs
                .Where(npc => !npc.FaceOption.IsBaseGame || npc.FaceGenOverride is not null)
                .OrderBy(npc => npc.BasePluginName, StringComparer.CurrentCultureIgnoreCase)
                .ThenBy(npc => npc.LocalFormIdHex, StringComparer.OrdinalIgnoreCase)
                .ToList();
            ItemCount.OnNext(npcs.Count);

            var builder = new StringBuilder();
            builder.AppendLine(
                "; Generated by EasyNPC Next. Adds the RSVIgnore keyword to every NPC this merge gives a modded face,");
            builder.AppendLine(
                "; so Racial Skin Variance (RSV) skips them and can't repaint their skin over the chosen appearance.");
            builder.AppendLine("; Safe to keep even without RSV installed - the keyword is simply never found.");
            builder.AppendLine();
            foreach (var npc in npcs)
            {
                CancellationToken.ThrowIfCancellationRequested();
                NextItemSync(npc.EditorId);
                // SPID form filter: keyword|strings|forms|... ; the NPC goes in the form filter.
                builder.Append("Keyword = RSVIgnore|NONE|0x")
                    .Append(npc.LocalFormIdHex)
                    .Append('~')
                    .AppendLine(npc.BasePluginName);
            }

            fs.Directory.CreateDirectory(settings.OutputDirectory);
            var outputPath = fs.Path.Combine(settings.OutputDirectory, OutputFileName);
            await fs.File.WriteAllTextAsync(outputPath, builder.ToString(), CancellationToken);
            log.Information(
                "Wrote RSV exclusion file for {Count} NPC(s) to {FileName}", npcs.Count, OutputFileName);
            return new Result { ExcludedNpcCount = npcs.Count };
        }
    }
}
